import { promises as fs } from 'fs';
import * as path from 'path';

/**
 * The RoboAgent STM32 fixture (`fixtures/stm32_ws/stm32_test` next to the vscode checkout, a
 * REQ-6 generated CMake library for STM32F103C8T6). When that folder is present it is copied
 * without its `build/` (a clean checkout); otherwise an identical inline copy is written.
 */
export async function writeStm32LibraryFixture(dest: string): Promise<'repo-fixture' | 'inline-copy'> {
	const repoFixture = path.resolve(__dirname, '..', '..', '..', '..', '..', 'fixtures', 'stm32_ws', 'stm32_test');
	try {
		await fs.access(path.join(repoFixture, 'CMakeLists.txt'));
		await fs.cp(repoFixture, dest, { recursive: true, filter: src => path.basename(src) !== 'build' });
		return 'repo-fixture';
	} catch {
		// fall through to the inline copy
	}
	const files: Record<string, string> = {
		'README.md': '# stm32_test — STM32 library (STM32F103C8T6)\n\nGenerated by RoboAgent (Mode: STM32).\n',
		'CMakeLists.txt': [
			'cmake_minimum_required(VERSION 3.22)',
			'set(CMAKE_TOOLCHAIN_FILE ${CMAKE_CURRENT_SOURCE_DIR}/cmake/arm-none-eabi.cmake)',
			'project(stm32_test C ASM)',
			'set(CMAKE_C_STANDARD 11)',
			'set(CMAKE_EXPORT_COMPILE_COMMANDS ON)',
			'set(MCU_FLAGS -mcpu=cortex-m3 -mthumb -mfloat-abi=soft)',
			'add_compile_options(${MCU_FLAGS} -Wall -Wextra -ffunction-sections -fdata-sections -fno-common)',
			'add_compile_options("$<$<CONFIG:Debug>:-Og;-g3>")',
			'add_compile_definitions(STM32F103xB USE_HAL_DRIVER)',
			'add_library(${PROJECT_NAME} STATIC',
			'  Src/stm32_test.c',
			')',
			'target_include_directories(${PROJECT_NAME} PUBLIC Inc)',
			'',
		].join('\n'),
		'cmake/arm-none-eabi.cmake': ARM_TOOLCHAIN_FILE,
		'Inc/stm32_test.h': '#ifndef STM32_TEST_H\n#define STM32_TEST_H\n\n#include <stdint.h>\n\nvoid stm32_test_init(void);\nuint32_t stm32_test_tick(void);\n\n#endif\n',
		'Src/stm32_test.c': '#include "stm32_test.h"\n\nstatic uint32_t s_ticks;\n\nvoid stm32_test_init(void)\n{\n    s_ticks = 0u;\n}\n\nuint32_t stm32_test_tick(void)\n{\n    return ++s_ticks;\n}\n',
	};
	await writeAll(dest, files);
	return 'inline-copy';
}

const ARM_TOOLCHAIN_FILE = [
	'set(CMAKE_SYSTEM_NAME Generic)',
	'set(CMAKE_SYSTEM_PROCESSOR arm)',
	'set(TOOLCHAIN_PREFIX arm-none-eabi-)',
	'set(CMAKE_C_COMPILER   ${TOOLCHAIN_PREFIX}gcc)',
	'set(CMAKE_ASM_COMPILER ${TOOLCHAIN_PREFIX}gcc)',
	'set(CMAKE_OBJCOPY      ${TOOLCHAIN_PREFIX}objcopy)',
	'set(CMAKE_SIZE         ${TOOLCHAIN_PREFIX}size)',
	'set(CMAKE_TRY_COMPILE_TARGET_TYPE STATIC_LIBRARY)',
	'set(CMAKE_FIND_ROOT_PATH_MODE_PROGRAM NEVER)',
	'',
].join('\n');

/**
 * A minimal bare-metal STM32F103 executable (vector table, reset handler, linker script, map
 * file), so build → size → map → flash can be exercised end to end without HAL sources.
 */
export async function writeStm32ExecutableFixture(dest: string): Promise<void> {
	await writeAll(dest, {
		'README.md': '# blinky — STM32F103C8T6 bare-metal test image\n',
		'CMakeLists.txt': [
			'cmake_minimum_required(VERSION 3.22)',
			'set(CMAKE_TOOLCHAIN_FILE ${CMAKE_CURRENT_SOURCE_DIR}/cmake/arm-none-eabi.cmake)',
			'project(blinky C)',
			'set(MCU_FLAGS -mcpu=cortex-m3 -mthumb -mfloat-abi=soft)',
			'add_compile_options(${MCU_FLAGS} -Wall -Wextra -ffunction-sections -fdata-sections -Og -g)',
			'add_executable(blinky.elf Src/main.c)',
			'target_link_options(blinky.elf PRIVATE ${MCU_FLAGS} -nostdlib -T${CMAKE_SOURCE_DIR}/STM32F103C8Tx_FLASH.ld -Wl,--gc-sections -Wl,-Map=${CMAKE_BINARY_DIR}/blinky.map)',
			'',
		].join('\n'),
		'cmake/arm-none-eabi.cmake': ARM_TOOLCHAIN_FILE,
		'STM32F103C8Tx_FLASH.ld': [
			'MEMORY {',
			'  FLASH (rx) : ORIGIN = 0x08000000, LENGTH = 64K',
			'  RAM (rwx)  : ORIGIN = 0x20000000, LENGTH = 20K',
			'}',
			'_estack = ORIGIN(RAM) + LENGTH(RAM);',
			'SECTIONS {',
			'  .isr_vector : { KEEP(*(.isr_vector)) } > FLASH',
			'  .text : { *(.text*) *(.rodata*) } > FLASH',
			'  _sidata = LOADADDR(.data);',
			'  .data : { _sdata = .; *(.data*) _edata = .; } > RAM AT > FLASH',
			'  .bss : { _sbss = .; *(.bss*) *(COMMON) _ebss = .; } > RAM',
			'}',
			'',
		].join('\n'),
		'Src/main.c': [
			'#include <stdint.h>',
			'',
			'extern uint32_t _estack, _sidata, _sdata, _edata, _sbss, _ebss;',
			'volatile uint32_t counter = 7;',
			'uint8_t buffer[1024];',
			'int main(void);',
			'',
			'void Reset_Handler(void)',
			'{',
			'\tuint32_t *src = &_sidata, *dst = &_sdata;',
			'\twhile (dst < &_edata) { *dst++ = *src++; }',
			'\tfor (dst = &_sbss; dst < &_ebss; ) { *dst++ = 0; }',
			'\tmain();',
			'\tfor (;;) { }',
			'}',
			'',
			'__attribute__((section(".isr_vector"), used)) void (* const vectors[])(void) = { (void (*)(void))&_estack, Reset_Handler };',
			'',
			'int main(void)',
			'{',
			'\tfor (;;) {',
			'\t\tcounter++;',
			'\t\tbuffer[counter & 1023u] = (uint8_t)counter;',
			'\t}',
			'}',
			'',
		].join('\n'),
	});
}

async function writeAll(dest: string, files: Record<string, string>): Promise<void> {
	for (const [rel, content] of Object.entries(files)) {
		const p = path.join(dest, rel);
		await fs.mkdir(path.dirname(p), { recursive: true });
		await fs.writeFile(p, content);
	}
}

/**
 * Blue Pill (STM32F103C8T6) debug image: blinks the PC13 LED, keeps globals to watch, and on
 * `fault_trigger = 1` reads an address with no memory behind it (a seeded precise BusFault,
 * escalated to HardFault). Built with plain `arm-none-eabi-gcc` (see {@link BLUEPILL_BUILD_ARGS}).
 */
export async function writeBluePillDebugFixture(dest: string): Promise<void> {
	await writeAll(dest, {
		'README.md': '# bluepill_debug — STM32F103C8T6 debug-agent test image (LED on PC13)\n',
		'bluepill.ld': [
			'MEMORY {',
			'  FLASH (rx) : ORIGIN = 0x08000000, LENGTH = 64K',
			'  RAM (rwx)  : ORIGIN = 0x20000000, LENGTH = 20K',
			'}',
			'_estack = ORIGIN(RAM) + LENGTH(RAM);',
			'SECTIONS {',
			'  .isr_vector : { KEEP(*(.isr_vector)) } > FLASH',
			'  .text : { *(.text*) *(.rodata*) } > FLASH',
			'  _sidata = LOADADDR(.data);',
			'  .data : { _sdata = .; *(.data*) _edata = .; } > RAM AT > FLASH',
			'  .bss : { _sbss = .; *(.bss*) *(COMMON) _ebss = .; } > RAM',
			'}',
			'',
		].join('\n'),
		'Src/main.c': [
			'#include <stdint.h>',
			'',
			'#define RCC_APB2ENR (*(volatile uint32_t *)0x40021018u)',
			'#define GPIOC_CRH   (*(volatile uint32_t *)0x40011004u)',
			'#define GPIOC_ODR   (*(volatile uint32_t *)0x4001100Cu)',
			'',
			'extern uint32_t _estack, _sidata, _sdata, _edata, _sbss, _ebss;',
			'',
			'struct sensor {',
			'\tuint16_t id;',
			'\tint16_t reading;',
			'};',
			'',
			'volatile uint32_t counter;',
			'volatile uint32_t fault_trigger;',
			'volatile struct sensor sensor = { 7, -3 };',
			'',
			'int main(void);',
			'',
			'void Reset_Handler(void)',
			'{',
			'\tuint32_t *src = &_sidata, *dst = &_sdata;',
			'\twhile (dst < &_edata) { *dst++ = *src++; }',
			'\tfor (dst = &_sbss; dst < &_ebss; ) { *dst++ = 0; }',
			'\tmain();',
			'\tfor (;;) { }',
			'}',
			'',
			'void HardFault_Handler(void)',
			'{',
			'\tfor (;;) { }',
			'}',
			'',
			'void Default_Handler(void)',
			'{',
			'\tfor (;;) { }',
			'}',
			'',
			'__attribute__((section(".isr_vector"), used)) void (* const vectors[])(void) = {',
			'\t(void (*)(void))&_estack, Reset_Handler, Default_Handler, HardFault_Handler,',
			'\tDefault_Handler, Default_Handler, Default_Handler,',
			'};',
			'',
			'static void delay(volatile uint32_t n)',
			'{',
			'\twhile (n--) { }',
			'}',
			'',
			'__attribute__((noinline)) void toggle_led(void)',
			'{',
			'\tGPIOC_ODR ^= (1u << 13);',
			'}',
			'',
			'/* No memory behind 0x60000000 on the C8 (no FSMC): a precise BusFault. */',
			'__attribute__((noinline)) uint32_t read_sensor_bus(void)',
			'{',
			'\treturn *(volatile uint32_t *)0x60000000u;',
			'}',
			'',
			'int main(void)',
			'{',
			'\tRCC_APB2ENR |= (1u << 4); /* IOPCEN */',
			'\tGPIOC_CRH = (GPIOC_CRH & ~(0xFu << 20)) | (0x2u << 20); /* PC13: output, push-pull, 2 MHz */',
			'\tfor (;;) {',
			'\t\tcounter++;',
			'\t\tsensor.reading = (int16_t)(counter & 0xFFu);',
			'\t\ttoggle_led();',
			'\t\tdelay(200000u);',
			'\t\tif (fault_trigger) {',
			'\t\t\tcounter += read_sensor_bus();',
			'\t\t}',
			'\t}',
			'}',
			'',
		].join('\n'),
	});
}

