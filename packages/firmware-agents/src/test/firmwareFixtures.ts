/**
 * The ESP32 debug fixture (ESP-IDF): a "sensor" loop with seeded bugs (NULL-pointer read,
 * failed assert, stack overflow, task watchdog), triggered by `fault_trigger` (from the
 * debugger) or by a console character. Two configurations: `sdkconfig.gdbstub` (live debugging
 * over the UART GDB stub) and `sdkconfig.coredump` (panic log + core dump on the UART, then halt).
 * The same sources were used to record the esp32-*.log and esp32-*.mi.txt fixtures on an ESP32.
 */
export async function writeEsp32DebugFixture(dest: string): Promise<void> {
	await writeAll(dest, {
		'CMakeLists.txt': 'cmake_minimum_required(VERSION 3.22)\ninclude($ENV{IDF_PATH}/tools/cmake/project.cmake)\nproject(esp32_debug)\n',
		'main/CMakeLists.txt': 'idf_component_register(SRCS "main.c" INCLUDE_DIRS "." PRIV_REQUIRES esp_system freertos)\n',
		'main/main.c': [
			'/*',
			' * RoboAgent ESP32 debug fixture: a blinking "sensor" task with seeded bugs.',
			' *',
			' * A bug is triggered by `fault_trigger` (set it from the debugger) or, when the console is not',
			' * owned by the GDB stub, by a character on UART0:',
			' *   1 / \'n\'  null-pointer read in read_sensor_bus()      -> LoadProhibited',
			' *   2 / \'a\'  failed assert in check_reading()            -> abort()',
			' *   3 / \'s\'  unbounded recursion in a small task          -> stack overflow',
			' *   4 / \'w\'  busy loop that never yields                  -> task watchdog',
			' */',
			'#include <assert.h>',
			'#include <stdint.h>',
			'#include <stdio.h>',
			'#include "freertos/FreeRTOS.h"',
			'#include "freertos/task.h"',
			'#include "esp_task_wdt.h"',
			'#include "sdkconfig.h"',
			'',
			'typedef struct {',
			'    uint32_t id;',
			'    int32_t reading;',
			'} sensor_t;',
			'',
			'volatile uint32_t counter;',
			'volatile uint32_t fault_trigger;',
			'sensor_t sensor = { .id = 7, .reading = 0 };',
			'static volatile uint32_t *sensor_bus;',
			'',
			'__attribute__((noinline)) int32_t read_sensor_bus(void)',
			'{',
			'    return (int32_t)*sensor_bus;',
			'}',
			'',
			'__attribute__((noinline)) void check_reading(int32_t reading)',
			'{',
			'    assert(reading >= 0 && "sensor reading must not be negative");',
			'}',
			'',
			'volatile uint32_t recursion_limit = 100000;',
			'',
			'__attribute__((noinline)) uint32_t recurse(uint32_t depth)',
			'{',
			'    volatile uint8_t frame[64];',
			'    frame[depth % sizeof(frame)] = (uint8_t)depth;',
			'    if (depth >= recursion_limit) {',
			'        return frame[0];',
			'    }',
			'    return recurse(depth + 1) + frame[0];',
			'}',
			'',
			'static void overflow_task(void *arg)',
			'{',
			'    printf("recursing: %lu\\n", (unsigned long)recurse(0));',
			'    vTaskDelete(NULL);',
			'}',
			'',
			'__attribute__((noinline)) void toggle_led(void)',
			'{',
			'    counter++;',
			'    sensor.reading = (int32_t)(counter & 0xFF);',
			'}',
			'',
			'static void run_seeded_bug(uint32_t bug)',
			'{',
			'    switch (bug) {',
			'    case 1:',
			'        sensor.reading = read_sensor_bus();',
			'        break;',
			'    case 2:',
			'        check_reading(-1);',
			'        break;',
			'    case 3:',
			'        xTaskCreate(overflow_task, "overflow", 1024, NULL, 5, NULL);',
			'        break;',
			'    case 4:',
			'        esp_task_wdt_add(NULL);',
			'        for (;;) {',
			'            counter++;',
			'        }',
			'        break;',
			'    default:',
			'        break;',
			'    }',
			'}',
			'',
			'static uint32_t console_command(void)',
			'{',
			'#if !CONFIG_ESP_SYSTEM_GDBSTUB_RUNTIME',
			'    switch (getchar()) {',
			'    case \'1\': case \'n\': return 1;',
			'    case \'2\': case \'a\': return 2;',
			'    case \'3\': case \'s\': return 3;',
			'    case \'4\': case \'w\': return 4;',
			'    default: break;',
			'    }',
			'#endif',
			'    return 0;',
			'}',
			'',
			'void app_main(void)',
			'{',
			'    printf("esp32_debug ready\\n");',
			'    for (;;) {',
			'        toggle_led();',
			'        uint32_t bug = fault_trigger ? fault_trigger : console_command();',
			'        if (bug) {',
			'            fault_trigger = 0;',
			'            printf("seeded bug %lu\\n", (unsigned long)bug);',
			'            run_seeded_bug(bug);',
			'        }',
			'        vTaskDelay(pdMS_TO_TICKS(100));',
			'    }',
			'}',
			'',
		].join('\n'),
		'sdkconfig.defaults': [
			'CONFIG_IDF_TARGET="esp32"',
			'CONFIG_COMPILER_OPTIMIZATION_DEBUG=y',
			'CONFIG_ESP_TASK_WDT_TIMEOUT_S=3',
			'CONFIG_ESP_TASK_WDT_PANIC=y',
			'CONFIG_FREERTOS_CHECK_STACKOVERFLOW_CANARY=y',
			'',
		].join('\n'),
		'sdkconfig.gdbstub': [
			'CONFIG_ESP_SYSTEM_GDBSTUB_RUNTIME=y',
			'CONFIG_ESP_SYSTEM_PANIC_GDBSTUB=y',
			'CONFIG_ESP_GDBSTUB_SUPPORT_TASKS=y',
			'',
		].join('\n'),
		'sdkconfig.coredump': [
			'CONFIG_ESP_SYSTEM_PANIC_PRINT_HALT=y',
			'CONFIG_ESP_COREDUMP_ENABLE_TO_UART=y',
			'CONFIG_ESP_COREDUMP_DATA_FORMAT_ELF=y',
			'CONFIG_FREERTOS_WATCHPOINT_END_OF_STACK=y',
			'',
		].join('\n'),
	});
}
